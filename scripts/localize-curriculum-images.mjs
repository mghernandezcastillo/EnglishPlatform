import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { createServer } from 'vite';

const root = process.cwd();
const outputDirectory = path.join(root, 'public', 'images', 'curriculum-remote');
const mappingFile = path.join(root, 'src', 'data', 'curriculumImageMap.ts');
const vite = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'silent' });
const urls = new Set();
const restoredLocalImageVersions = {
  '/images/prep_between.jpg': '/images/prep_between.jpg?v=restored-20260820',
  '/images/directions_ask.jpg': '/images/directions_ask.jpg?v=restored-20260820',
  '/images/prep_in.jpg': '/images/prep_in.jpg?v=restored-20260820',
  '/images/prep_on.jpg': '/images/prep_on.jpg?v=restored-20260820',
  '/images/prep_under.jpg': '/images/prep_under.jpg?v=restored-20260820',
  '/images/prep_next_to.jpg': '/images/prep_next_to.jpg?v=restored-20260820',
  '/images/prep_across.jpg': '/images/prep_across.jpg?v=restored-20260820',
  '/images/directions_give.jpg': '/images/directions_give.jpg?v=restored-20260820',
  '/images/adults_c10_emoji.jpg': '/images/adults_c10_emoji.jpg?v=restored-20260820',
  '/images/teens_complete.jpg': '/images/teens_complete.jpg?v=restored-20260820',
  '/images/adults_c10_homework.jpg': '/images/adults_c10_homework.jpg?v=restored-20260820',
  '/images/adults_c10_video.jpg': '/images/adults_c10_video.jpg?v=restored-20260820',
  '/images/teens_welcome.jpg': '/images/teens_welcome.jpg?v=restored-20260820',
  '/images/teens_social_welcome.jpg': '/images/teens_social_welcome.jpg?v=restored-20260820',
  '/images/teens_apps.jpg': '/images/teens_apps.jpg?v=restored-20260820',
};

try {
  const existingMap = (await vite.ssrLoadModule('/src/data/curriculumImageMap.ts')).curriculumImageMap || {};
  Object.keys(existingMap).forEach((url) => urls.add(url));
  const sources = [
    ['/src/data/curriculum.ts', 'curriculumLevels'],
    ['/src/data/curriculumKids.ts', 'curriculumKidsLevels'],
    ['/src/data/curriculumTeens.ts', 'curriculumTeensLevels'],
  ];
  for (const [modulePath, exportName] of sources) {
    const levels = (await vite.ssrLoadModule(modulePath))[exportName];
    for (const level of levels) {
      for (const lesson of level.classes) {
        for (const section of lesson.sections) {
          for (const slide of section.slides) {
            if (/^https:\/\/images\.unsplash\.com\//i.test(slide.imageUrl || '')) urls.add(slide.imageUrl);
          }
        }
      }
    }
  }
} finally {
  await vite.close();
}

fs.mkdirSync(outputDirectory, { recursive: true });
const mapping = {};

for (const [index, url] of [...urls].sort().entries()) {
  const photoId = url.match(/\/photo-([^?]+)/i)?.[1]?.replace(/[^a-z0-9-]/gi, '-') || `image-${index + 1}`;
  let filename = `${photoId}.jpg`;
  let destination = path.join(outputDirectory, filename);
  const existingPng = path.join(outputDirectory, `${photoId}.png`);
  if (fs.existsSync(existingPng)) {
    filename = `${photoId}.png`;
    destination = existingPng;
  }

  const verification = spawnSync('curl.exe', ['-s', '-o', 'NUL', '-w', '%{http_code}', url], { encoding: 'utf8' });
  const httpCode = verification.stdout.trim();
  if (verification.status !== 0 || httpCode !== '200') {
    throw new Error(`No se pudo verificar ${url}. curl devolvió ${httpCode || verification.stderr || verification.status}.`);
  }

  if (!fs.existsSync(destination) || fs.statSync(destination).size === 0) {
    const download = spawnSync('curl.exe', ['-L', '--fail', '--silent', '--show-error', '-o', destination, url], { encoding: 'utf8' });
    if (download.status !== 0) throw new Error(`No se pudo descargar ${url}: ${download.stderr}`);
  }
  const signature = fs.readFileSync(destination).subarray(0, 8);
  const isPng = signature.equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]));
  if (isPng && !destination.endsWith('.png')) {
    const pngDestination = path.join(outputDirectory, `${photoId}.png`);
    fs.renameSync(destination, pngDestination);
    filename = `${photoId}.png`;
    destination = pngDestination;
  }
  const publicPath = `/images/curriculum-remote/${filename}`;
  mapping[url] = publicPath;
  console.log(`[${index + 1}/${urls.size}] ${httpCode} ${publicPath}`);
}

const generated = `// Generated by scripts/localize-curriculum-images.mjs.\n` +
  `// Keeps curriculum visuals independent from external hotlink availability.\n` +
  `import type { CurriculumLevel } from '../types';\n\n` +
  `export const curriculumImageMap: Record<string, string> = ${JSON.stringify(mapping, null, 2)};\n\n` +
  `const restoredLocalImageVersions: Record<string, string> = ${JSON.stringify(restoredLocalImageVersions, null, 2)};\n\n` +
  `export function localizeCurriculumImages(levels: CurriculumLevel[]) {\n` +
  `  for (const level of levels) {\n` +
  `    for (const lesson of level.classes) {\n` +
  `      for (const section of lesson.sections) {\n` +
  `        for (const slide of section.slides) {\n` +
  `          if (!slide.imageUrl) continue;\n` +
  `          const localized = curriculumImageMap[slide.imageUrl] || slide.imageUrl;\n` +
  `          const cleanPath = localized.split(/[?#]/)[0];\n` +
  `          slide.imageUrl = restoredLocalImageVersions[cleanPath] || localized;\n` +
  `        }\n` +
  `      }\n` +
  `    }\n` +
  `  }\n` +
  `}\n`;

fs.writeFileSync(mappingFile, generated, 'utf8');
console.log(`Mapa generado: ${mappingFile} (${urls.size} imágenes).`);
