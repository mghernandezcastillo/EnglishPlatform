const banks: Record<Audience, Record<string, QuestionTuple[]>> = {
  adulto: adultBanks,
  adolescente: teenBanks,
  niño: kidsBanks,
};

export function getOralQuestionBank(levelId: string, studentType?: string): OralQuestion[] {
  const audience: Audience = studentType === 'niño'
    ? 'niño'
    : studentType === 'adolescente'
      ? 'adolescente'
      : 'adulto';

  return (banks[audience][levelId] || []).map(([topic, question]) => ({ topic, question }));
}
